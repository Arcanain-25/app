// Инициализация распознавания речи
const voiceToggleButton = document.getElementById("voice-toggle");
let recognition;

if ('webkitSpeechRecognition' in window) {
    recognition = new webkitSpeechRecognition();
    recognition.lang = 'ru-RU';
    recognition.interimResults = false;
    recognition.maxAlternatives = 1;

    // При завершении распознавания
    recognition.onresult = function(event) {
        let speechResult = event.results[0][0].transcript.toLowerCase();
        document.getElementById("assistant-input").value = speechResult;
        handleInput({ key: 'Enter' });
    };

    recognition.onerror = function(event) {
        console.error("Ошибка распознавания речи:", event.error);
    };
    
    // Обработчик для кнопки голосового ввода
    voiceToggleButton.addEventListener("click", function() {
        if (recognition) {
            recognition.start();
            console.log("Голосовое распознавание начато...");
        }
    });
} else {
    console.log("Ваш браузер не поддерживает Web Speech API");
}







