// История для озвучивания
const storyText = `
    В темном и безжалостном веке мир начал рушиться. Небо потемнело, а туман заполнил землю.
    Великая сила, Су́мрак, дух разрушения, пробудилась в глубинах древних гор.
    Он был стар и силен, его задача — вернуть мир в состояние хаоса.

    Среди разрушений появился Лиан — простой путник, не обладавший великими силами, но полон решимости.
    Он верил, что даже в темноте можно найти свет. Лиан отправился в поисках Древнего Камня,
    который мог бы остановить Су́мрак.

    Проходя через испытания, Лиан дошел до Великой Обсерватории, где, наконец, столкнулся с Су́мраком.
    Но в последний момент, с помощью древнего артефакта, он смог пробудить силу мира и победить разрушение.
`;

// Функция для воспроизведения истории с озвучиванием
function startStory() {
    // Озвучиваем текст истории
    playVoice();  // Вызов функции для воспроизведения звука из iiss.js

    // Для примера, просто выводим текст истории в консоль
    console.log(storyText);
}

// Запуск истории при загрузке страницы или по клику на кнопку
startStory();
// Убедимся, что функция speakText доступна
if (typeof window !== 'undefined' && window.speakText) {
    window.speakText(storyText);  // Автоматически озвучиваем историю при загрузке
}